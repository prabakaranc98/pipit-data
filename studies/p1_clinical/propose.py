"""Turn the evidence into the next round: a lab model reads the hypothesis table and the failing cells and proposes
sharper key questions, new case families with planted truth, and predictions. Nothing proposed here runs until a
human has read it; the output is proposals.md, marked as such. Usage: uv run python studies/p1_clinical/propose.py"""

from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from study import HERE, subject  # noqa: E402

PROMPT = """You are helping design the next round of a pre-registered audit of a small clinical decision model.
Below is the report of the first round: an objective, a tree of hypotheses and key questions, and the evidence per cell.

For every hypothesis whose status is "supported" or "insufficient", propose:
1. Two sharper key questions (each a falsifiable statement about the model, one sentence).
2. Two new case families to test them. For each: the clinical scenario (one or two sentences), the critical fact and how it is expressed, the three conditions (critical, benign, absent) and the expected answer for each, and what result would refute the hypothesis.
3. One prediction with a number: the failure rate you expect in the critical condition, and why.
Keep every case synthetic and free of identifiers. Mark anything that depends on clinical knowledge you are unsure about.
Use plain headings per hypothesis. Do not propose anything for hypotheses marked "refuted".

REPORT:
{report}"""


def main() -> None:
    report = (HERE / "report.md").read_text()
    table = re.search(r"### Hypothesis tree.*?\n\n### Cells\n\n(.*?)\n\nReading", report, re.S)
    head = report.split("## ", 1)[0]
    body = report[report.find("### Hypothesis tree") :]
    _, proposer = subject(HERE / "models" / "proposer.yaml", max_calls=3)
    r = proposer(PROMPT.format(report=head + body[:12000]), temperature=0.3, max_tokens=3000, role="proposer")
    text = (
        "# Proposals for round 2 (for human review; nothing here has been run)\n\n"
        + f"Generated by the lab model in models/proposer.yaml (answered by {r['model']} via {r['provider']}) from report.md.\n\n"
        + r["text"].strip()
        + "\n"
    )
    (HERE / "proposals.md").write_text(text)
    print(text[:3000])
    if table is None:
        print("(hypothesis table not located; the whole report was sent)")


if __name__ == "__main__":
    main()
